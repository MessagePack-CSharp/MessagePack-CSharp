using BenchmarkDotNet.Attributes;
using MessagePack;

// End-to-end companion of NullableReadBenchmark on the AnswerBenchmark payload: the generated formatters against
// twins of them whose int? / bool? member reads use the one-window candidates (61 members in this graph).
//   Generated - the default resolver: the source generator's formatters. Since the readers were adopted this is
//               the AFTER: its member reads are buffer.ReadNullableInt32() / ReadNullableBoolean()
//   TwinCopy  - AnswerTwins.Copy: the generator's output from BEFORE the change (`TryReadNil() ? default : ReadX()`),
//               compiled as hand-registered formatters. Measured against Generated while both emitted the same
//               reads: 58 instructions and 1% apart, so it stands in for the old generated code
//   TwinFused - AnswerTwins.Fused: Copy with the sandbox candidates (ReadInt32OrNilInline / ReadBooleanOrNilInline)
//               in the member reads: the prototype the adoption was decided on
// Setup checks that every row rebuilds the payload byte for byte.
//
// MEASURED before the adoption, when Generated still emitted the pair (i7-13700KF, .NET 11, ShortRun, not elevated, ns):
//   run 2: Generated 869   TwinCopy 873   TwinFused 831   (Fused / Copy 0.95)
//   run 4: Generated 876   TwinCopy 888   TwinFused 837   (0.94)
//   run 3: Generated 957   TwinCopy 912   TwinFused 925   (1.01; noisy, TwinFused StdDev 70)
// Instructions per op (elevated run): Generated 20,241   TwinCopy 20,299   TwinFused 19,049 (-6.2%); branches
// 3,984 -> 3,838, mispredicts 13 in every row. The twins stand in for the generated formatters (58 instructions apart).
//
// MEASURED after the adoption (Generated now reads through ReadNullableInt32 / ReadNullableBoolean), ns:
//   run 1: TwinCopy 878   Generated 837   TwinFused 841   (Generated / TwinCopy 0.95)
//   run 3: TwinCopy 912   Generated 868   TwinFused 855   (0.95)
//   run 4: TwinCopy 936   Generated 862   TwinFused 872   (0.92)
//   run 2: TwinCopy 913   Generated 934   TwinFused 859   (1.02; noisy, Generated StdDev 90)
// Instructions per op (elevated run): TwinCopy 20,240   Generated 18,635 (-7.9%)   TwinFused 18,912; branches
// 3,966 -> 3,739, mispredicts 10 in every row.
// After every kind got its own helper (this graph only has int? and bool?, so nothing should move): run 1 TwinCopy 880
// Generated 842 (0.96), run 2 942 / 914 (0.97, noisy); instructions 20,351 -> 18,833 (-7.5%).
// The twin files are generated by AnswerTwinFormatters.make.py (arguments: the directory holding the generator's
// output for a copy of the Answer model built with EmitCompilerGeneratedFiles, and this directory).
[MemoryDiagnoser]
public class AnswerNullableReadEndToEndBenchmark
{
    byte[] payload = null!;
    MessagePackSerializerOptions copy = null!;
    MessagePackSerializerOptions fused = null!;

    [GlobalSetup]
    public void Setup()
    {
        payload = MessagePackSerializer.Serialize(AnswerBenchmark.CreateAnswer());
        copy = new MessagePackSerializerOptions(new MessagePackFormatterResolver(
        [
            new AnswerTwins.Copy.TwinFormatterFactory(),
            BuiltInFormatterFactory.Instance,
            GenericFormatterFactory.Instance,
        ]));
        fused = new MessagePackSerializerOptions(new MessagePackFormatterResolver(
        [
            new AnswerTwins.Fused.TwinFormatterFactory(),
            BuiltInFormatterFactory.Instance,
            GenericFormatterFactory.Instance,
        ]));

        foreach (var (name, answer) in new (string, Answer)[] { (nameof(Generated), Generated()), (nameof(TwinCopy), TwinCopy()), (nameof(TwinFused), TwinFused()) })
        {
            if (!MessagePackSerializer.Serialize(answer).AsSpan().SequenceEqual(payload))
            {
                throw new InvalidOperationException($"{name} does not roundtrip the payload");
            }
        }
        if (!MessagePackSerializer.Serialize(AnswerBenchmark.CreateAnswer(), copy).AsSpan().SequenceEqual(payload)
            || !MessagePackSerializer.Serialize(AnswerBenchmark.CreateAnswer(), fused).AsSpan().SequenceEqual(payload))
        {
            throw new InvalidOperationException("the twins serialize differently from the generated formatters");
        }
    }

    [Benchmark(Baseline = true)]
    public Answer Generated() => MessagePackSerializer.Deserialize<Answer>(payload)!;

    [Benchmark]
    public Answer TwinCopy() => MessagePackSerializer.Deserialize<Answer>(payload, copy)!;

    [Benchmark]
    public Answer TwinFused() => MessagePackSerializer.Deserialize<Answer>(payload, fused)!;
}
