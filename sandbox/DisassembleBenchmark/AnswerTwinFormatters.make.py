"""Turns the generator's output for the Answer model into two sets of twin formatters
for sandbox/DisassembleBenchmark: Copy (the generated code as is) and Fused (the nullable int / bool member reads
replaced by the candidate readers).

The input has to be output of the generator from BEFORE it emitted ReadNullableX (the member reads are matched by
the old `TryReadNil() ? default(T?) : ReadX()` text); the committed twins were made from that."""
import io
import re
import sys

gen_dir, out_dir = sys.argv[1], sys.argv[2]
types = ['Answer', 'Comment', 'ShallowUser', 'BadgeCount']

INT_READ = 'buffer.TryReadNil() ? default(int?) : buffer.ReadInt32()'
BOOL_READ = 'buffer.TryReadNil() ? default(bool?) : buffer.ReadBoolean()'

for variant in ['Copy', 'Fused']:
    parts = []
    replaced = 0
    for t in types:
        s = io.open(f'{gen_dir}/Sample_{t}Formatter.g.cs', encoding='utf-8-sig').read().replace('\r\n', '\n')
        # body of the namespace block only
        start = s.index('namespace MessagePack.Generated')
        s = s[start:]
        s = s.replace('namespace MessagePack.Generated', f'namespace AnswerTwins.{variant}')
        s = s.replace(f'Sample_{t}Formatter', f'{t}Formatter')
        s = s.replace('global::Sample.', 'global::')
        s = re.sub(r'(?<![\w.:])Formatters\.', 'global::MessagePack.Formatters.', s)
        if variant == 'Fused':
            # switch sections share one declaration space, so every out variable gets its own name
            while INT_READ in s:
                replaced += 1
                s = s.replace(INT_READ, f'buffer.ReadInt32OrNilInline(out var nv{replaced}) ? nv{replaced} : default(int?)', 1)
            while BOOL_READ in s:
                replaced += 1
                s = s.replace(BOOL_READ, f'buffer.ReadBooleanOrNilInline(out var nv{replaced}) ? nv{replaced} : default(bool?)', 1)
        parts.append(s.rstrip() + '\n')

    header = f'''// <auto-generated/>
// Twin of the source generator's output for the Answer model ({variant}), produced by a script from the generated
// files so AnswerNullableReadEndToEndBenchmark can A/B a change to the emitted member reads without touching the
// generator. Copy is the generated code unchanged; Fused differs only in the nullable int / bool member reads
// (NullableReadCandidates). Do not edit by hand.
#pragma warning disable
#nullable enable annotations

'''
    factory = f'''
namespace AnswerTwins.{variant}
{{
    public sealed partial class TwinFormatterFactory : global::MessagePack.MessagePackFormatterFactory
    {{
        public override object? CreateFormatter<TWriteBuffer, TReadBuffer>(global::System.Type type)
        {{
            if (type == typeof(global::Answer)) return new AnswerFormatter<TWriteBuffer, TReadBuffer>();
            if (type == typeof(global::Comment)) return new CommentFormatter<TWriteBuffer, TReadBuffer>();
            if (type == typeof(global::ShallowUser)) return new ShallowUserFormatter<TWriteBuffer, TReadBuffer>();
            if (type == typeof(global::BadgeCount)) return new BadgeCountFormatter<TWriteBuffer, TReadBuffer>();
            return null;
        }}
    }}
}}
'''
    io.open(f'{out_dir}/AnswerTwinFormatters.{variant}.g.cs', 'w', encoding='utf-8', newline='\n').write(header + '\n'.join(parts) + factory)
    print(variant, 'written; member reads replaced:', replaced)
