    // the production path is SipHash-1-3 (see SipHash.Hash64.cs for the rationale), so
    // it pins against Rust's sip13 vectors instead of the 2-4 vectors.h
    [Fact]
    public void Hash64_MatchesRustSip13Vectors()
    {
        var k = Key();
        var k0 = BinaryPrimitives.ReadUInt64LittleEndian(k);
        var k1 = BinaryPrimitives.ReadUInt64LittleEndian(k.AsSpan(8));
        for (var inlen = 0; inlen < VectorsSip13.Length; inlen++)
        {
            var expected = BinaryPrimitives.ReadUInt64LittleEndian(VectorsSip13[inlen]);
            Assert.Equal(expected, SipHash.Hash64(Input(inlen), k0, k1));
        }
    }

    // Hash64Fixed must agree with the span path for every length 0..8, and for
    // lengths < 8 garbage in the unused upper bytes must be masked off
    [Fact]
    public void Hash64Fixed_MatchesSpanPath_AndMasksUnusedBytes()
    {
        var rng = new Random(7777);
        var k = new byte[16];
        rng.NextBytes(k);
        var k0 = BinaryPrimitives.ReadUInt64LittleEndian(k);
        var k1 = BinaryPrimitives.ReadUInt64LittleEndian(k.AsSpan(8));

        var bytes = new byte[8];
        for (var length = 0; length <= 8; length++)
        {
            rng.NextBytes(bytes);
            var expected = SipHash.Hash64(bytes.AsSpan(0, length), k0, k1);

            var bits = BinaryPrimitives.ReadUInt64LittleEndian(bytes);
            if (length < 8)
            {
                bits &= (1UL << (length * 8)) - 1UL; // clean upper bytes
                Assert.Equal(expected, SipHash.Hash64Fixed(bits, length, k0, k1));

                var garbage = bits | (~0UL << (length * 8)); // all-ones upper bytes
                Assert.Equal(expected, SipHash.Hash64Fixed(garbage, length, k0, k1));
            }
            else
            {
                Assert.Equal(expected, SipHash.Hash64Fixed(bits, length, k0, k1));
            }
        }
    }

    [Fact]
    public void Hash64Fixed16_MatchesSpanPath()
    {
        var rng = new Random(5555);
        var k = new byte[16];
        rng.NextBytes(k);
        var k0 = BinaryPrimitives.ReadUInt64LittleEndian(k);
        var k1 = BinaryPrimitives.ReadUInt64LittleEndian(k.AsSpan(8));

        var bytes = new byte[16];
        for (var trial = 0; trial < 8; trial++)
        {
            rng.NextBytes(bytes);
            var expected = SipHash.Hash64(bytes, k0, k1);
            var bits0 = BinaryPrimitives.ReadUInt64LittleEndian(bytes);
            var bits1 = BinaryPrimitives.ReadUInt64LittleEndian(bytes.AsSpan(8));
            Assert.Equal(expected, SipHash.Hash64Fixed16(bits0, bits1, k0, k1));
        }
    }

